def _parse_f5():
    g = {}
    lines = _F5_RAW.strip('\n').split('\n')
    i = 0
    while i < len(lines):
        name = lines[i]
        n = 6 if name in ('g', 'j', 'p', 'q', 'y') else 5
        rows = lines[i + 1:i + 1 + n]
        i += 1 + n
        w = max(len(r) for r in rows)
        arr = np.zeros((7, w), bool)
        for y, r in enumerate(rows):
            for x, ch in enumerate(r):
                arr[y, x] = ch == '#'
        g[name] = arr
    g[' '] = np.zeros((7, 2), bool)
    return g


_F5 = _parse_f5()


def _glyph5(ch):
    if ch in _F5:
        return _F5[ch]
    if ch.upper() in _F5:
        return _F5[ch.upper()]
    return _F5['?']


def text_size(s, font='5'):
    if font == '3':
        return (4 * len(s) - 1 if s else 0), 5
    w = 0
    for ch in s:
        w += _glyph5(ch).shape[1] + 1
    return max(0, w - 1), 7


def draw_text(canvas, s, x, y, c, font='5', shadow=None, align='left'):
    from .px import rgba
    w, _ = text_size(s, font)
    if align == 'center':
        x -= w // 2
    elif align == 'right':
        x -= w
    x, y = int(x), int(y)
    passes = ([(shadow, 1, 1)] if shadow is not None else []) + [(c, 0, 0)]
    for col, dx, dy in passes:
        cx = x
        for ch in s:
            g = _glyph3(ch) if font == '3' else _glyph5(ch)
            ys, xs = np.nonzero(g)
            for gy, gx in zip(ys, xs):
                canvas.px(cx + gx + dx, y + gy + dy, col)
            cx += (4 if font == '3' else g.shape[1] + 1)


def text_mask(s, font='5'):
    """Boolean mask of rendered text (for scaling / effects)."""
    w, h = text_size(s, font)
    m = np.zeros((h, max(w, 1)), bool)
    cx = 0
    for ch in s:
        g = _glyph3(ch) if font == '3' else _glyph5(ch)
        gh, gw = g.shape
        m[:gh, cx:cx + gw] |= g
        cx += (4 if font == '3' else gw + 1)
    return m
